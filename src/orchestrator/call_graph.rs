//! SYSTEM CALL GRAPHS AS GRAPH CONTAINERS (operator 2026-11-11: "see the call graphs even without running a prompt").
//!
//! The system's own call graphs — the orchestration walk (stages → the functions that make model calls → the call sites), the background
//! loops' model-call sites, and the call routes with the guardrail layers on each — are extracted from the source and the registries by
//! `tools/call-graph/extract_system_call_graph.mjs` into ONE asset, `assets/call_graphs/system_call_graph.json`. This module:
//!
//!   * [`ensure_system_call_graphs`] — at host boot (workspace load) creates ONE graph container per graph (`Derived`, content pointed at
//!     `<data_dir>/call_graphs/<key>.json` through `object_store_path`, readable with `GetContainerContent` like every other body) and
//!     REFRESHES the body in place when the asset changed. Idempotent: the container ids and body hashes live in
//!     `<data_dir>/call_graphs/containers.json`; a container that still exists with an unchanged body is left alone, a deleted one is
//!     recreated, a changed body is rewritten without a new container. Boot is never blocked, but a failure is retried by the caller (lib.rs) until every graph is ensured — it is not dropped.
//!   * [`system_graphs_view`] — what `GET /callgraph/system` returns: the graphs as stored plus each graph's container id.
//!   * [`live_for_trace`] — what `GET /callgraph/live` returns: the executed calls (`capture/call_spans.jsonl`) and the stage events
//!     (`walk_metrics.jsonl`) of ONE walk's trace, so the UI can overlay "what actually ran" on the static graph. Read-only, never a model call.
//!
//! NO fixed caps and NO scores: an edge is present or absent, a call ran or it did not. A call row is written when the call FINISHES, so a call
//! still in flight is not in the live view (the pipeline-progress frames on `/ws` show those); this is stated in the response, not hidden.
//!
//! The asset is regenerated by running the extractor (it has a `--check` mode); the host never rewrites it. If the asset is missing the
//! module reports that plainly (`available: false`) rather than inventing a graph.

use super::StoreAccess;
use crate::types::container::{
    CompressionType, Container, ContainerType, Context, GlobalState, IntegrityData, LocalState, Metadata, Modality, StoragePointers,
    TraversalHints,
};
use serde_json::{json, Value};
use std::io::BufRead;
use std::path::PathBuf;
use std::sync::Arc;

/// Path of the asset under the resolved assets dir.
pub const ASSET_REL: &str = "call_graphs/system_call_graph.json";

fn data_dir() -> PathBuf {
    PathBuf::from(std::env::var("OZONE_ZSEI_DATA_DIR").unwrap_or_else(|_| "zsei_data".to_string()))
}

fn registry_path() -> PathBuf {
    data_dir().join("call_graphs/containers.json")
}

fn now_secs() -> u64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0)
}

/// The generated asset, parsed. `None` when it is missing or not valid JSON (the caller says so; nothing is invented).
pub fn load_asset() -> Option<Value> {
    let path = crate::bootstrap::BootstrapManager::resolve_assets_dir().join(ASSET_REL);
    let text = std::fs::read_to_string(&path).ok()?;
    serde_json::from_str::<Value>(&text).ok().filter(|v| v.get("graphs").map(|g| g.is_array()).unwrap_or(false))
}

fn read_registry() -> serde_json::Map<String, Value> {
    std::fs::read_to_string(registry_path())
        .ok()
        .and_then(|t| serde_json::from_str::<Value>(&t).ok())
        .and_then(|v| v.as_object().cloned())
        .unwrap_or_default()
}

fn write_registry(map: &serde_json::Map<String, Value>) {
    let path = registry_path();
    if let Some(dir) = path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    if let Ok(text) = serde_json::to_string_pretty(&Value::Object(map.clone())) {
        // temp + rename: a crash mid-write must not leave a truncated registry (the ids in it are what make the next boot idempotent)
        let tmp = path.with_extension(format!("tmp-{}", std::process::id()));
        if std::fs::write(&tmp, text).is_ok() {
            let _ = std::fs::rename(&tmp, &path);
        }
    }
}

fn hash_hex(text: &str) -> String {
    blake3::hash(text.as_bytes()).to_hex().to_string()
}

/// One graph's body exactly as stored in its content file.
fn graph_body(asset: &Value, graph: &Value) -> Value {
    json!({
        "kind": "system_call_graph",
        "key": graph["key"],
        "title": graph["title"],
        "generator": asset["generator"],
        "inputs_sha256": asset["inputs_sha256"],
        "notes": asset["notes"],
        "nodes": graph["nodes"],
        "edges": graph["edges"],
    })
}

fn build_container(key: &str, title: &str, rel_path: &str, now: u64) -> Container {
    Container {
        global_state: GlobalState { container_id: 0, parent_id: 0, child_ids: vec![], child_count: 0, version: 1 },
        local_state: LocalState {
            metadata: Metadata {
                container_type: ContainerType::Derived,
                modality: Modality::Unknown,
                created_at: now,
                updated_at: now,
                provenance: "system-call-graph".to_string(),
                permissions: 0,
                owner_id: 0,
                name: Some(format!("Call graph: {}", title)),
                materialized_path: Some(format!("/CallGraphs/{}", key)),
            },
            context: Context {
                keywords: vec!["call graph".to_string(), format!("{} call graph", key), "orchestration".to_string()],
                topics: vec!["call graph".to_string()],
                ..Default::default()
            },
            storage: StoragePointers {
                db_shard_id: None,
                vector_index_ref: None,
                object_store_path: Some(rel_path.to_string()),
                compression_type: CompressionType::None,
            },
            hints: TraversalHints::default(),
            integrity: IntegrityData::default(),
            file_context: None,
            code_context: None,
            text_context: None,
            external_ref: None,
        },
    }
}

/// What one ensure pass did (logged by the caller; also returned so a test or a future endpoint can read it).
#[derive(Debug, Default, Clone, PartialEq)]
pub struct EnsureReport {
    pub created: Vec<String>,
    pub refreshed: Vec<String>,
    pub unchanged: Vec<String>,
    pub failed: Vec<String>,
    pub asset_missing: bool,
}

/// Create / refresh the graph containers from the asset. Idempotent; the caller retries until `failed` is empty and the asset was found.
pub async fn ensure_system_call_graphs(store: &Arc<dyn StoreAccess>) -> EnsureReport {
    let mut report = EnsureReport::default();
    let Some(asset) = load_asset() else {
        report.asset_missing = true;
        tracing::warn!("call graphs: assets/{} not found — nothing materialised (run tools/call-graph/extract_system_call_graph.mjs)", ASSET_REL);
        return report;
    };
    let graphs: Vec<Value> = asset["graphs"].as_array().cloned().unwrap_or_default();
    let mut registry = read_registry();
    let mut registry_dirty = false;
    for graph in &graphs {
        let Some(key) = graph["key"].as_str().map(|s| s.to_string()) else { continue };
        let title = graph["title"].as_str().unwrap_or(&key).to_string();
        let body = graph_body(&asset, graph);
        let Ok(text) = serde_json::to_string_pretty(&body) else {
            report.failed.push(key);
            continue;
        };
        let hash = hash_hex(&text);
        let rel = format!("call_graphs/{}.json", key);
        let abs = data_dir().join(&rel);
        let known_id = registry.get(&key).and_then(|e| e.get("container_id")).and_then(|v| v.as_u64());
        let known_hash = registry.get(&key).and_then(|e| e.get("hash")).and_then(|v| v.as_str()).map(|s| s.to_string());
        let exists = match known_id {
            Some(id) => matches!(store.get_container(id).await, Ok(Some(_))),
            None => false,
        };
        let write_body = || -> bool {
            if let Some(dir) = abs.parent() {
                if std::fs::create_dir_all(dir).is_err() {
                    return false;
                }
            }
            let tmp = abs.with_extension(format!("tmp-{}", std::process::id()));
            std::fs::write(&tmp, &text).is_ok() && std::fs::rename(&tmp, &abs).is_ok()
        };
        if exists {
            if known_hash.as_deref() == Some(hash.as_str()) && abs.exists() {
                report.unchanged.push(key);
                continue;
            }
            // same container, new body: rewrite the content file in place
            if write_body() {
                registry.insert(key.clone(), json!({ "container_id": known_id, "hash": hash }));
                registry_dirty = true;
                report.refreshed.push(key);
            } else {
                report.failed.push(key);
            }
            continue;
        }
        // missing (first boot, or the container was deleted): body first, then the container that points at it
        if !write_body() {
            report.failed.push(key);
            continue;
        }
        let container = build_container(&key, &title, &rel, now_secs());
        let Ok(value) = serde_json::to_value(&container) else {
            report.failed.push(key);
            continue;
        };
        match store.create_container(0, value).await {
            Ok(id) => {
                registry.insert(key.clone(), json!({ "container_id": id, "hash": hash }));
                registry_dirty = true;
                report.created.push(key);
            }
            Err(e) => {
                tracing::warn!(graph = %key, error = %e, "call graphs: container creation failed (the caller retries)");
                report.failed.push(key);
            }
        }
    }
    if registry_dirty {
        write_registry(&registry);
    }
    tracing::info!(
        created = report.created.len(),
        refreshed = report.refreshed.len(),
        unchanged = report.unchanged.len(),
        failed = report.failed.len(),
        "call graphs: system call graph containers ensured"
    );
    report
}

/// `GET /callgraph/system` — the graphs (from the asset, so the view works even before the containers exist) with each graph's container
/// id from the registry (`null` until the ensure pass created it).
pub fn system_graphs_view() -> Value {
    let Some(asset) = load_asset() else {
        return json!({
            "success": true,
            "available": false,
            "note": format!("assets/{ASSET_REL} is missing — run tools/call-graph/extract_system_call_graph.mjs"),
            "graphs": [],
        });
    };
    let registry = read_registry();
    let graphs: Vec<Value> = asset["graphs"]
        .as_array()
        .map(|a| {
            a.iter()
                .map(|g| {
                    let key = g["key"].as_str().unwrap_or("");
                    let mut out = g.clone();
                    if let Some(obj) = out.as_object_mut() {
                        obj.insert("container_id".to_string(), registry.get(key).and_then(|e| e.get("container_id")).cloned().unwrap_or(Value::Null));
                    }
                    out
                })
                .collect()
        })
        .unwrap_or_default();
    json!({
        "success": true,
        "available": true,
        "generator": asset["generator"],
        "inputs_sha256": asset["inputs_sha256"],
        "notes": asset["notes"],
        "graphs": graphs,
    })
}

/// Rows of a JSONL file whose `trace_id` equals `trace_id`, read as a stream (the files are append-only and can be large; a cheap substring
/// test skips the JSON parse for every other line). No row cap: every row of the trace is returned.
fn rows_for_trace(path: &std::path::Path, trace_id: &str) -> Vec<Value> {
    let Ok(f) = std::fs::File::open(path) else { return Vec::new() };
    std::io::BufReader::new(f)
        .lines()
        .map_while(Result::ok)
        .filter(|l| l.contains(trace_id))
        .filter_map(|l| serde_json::from_str::<Value>(&l).ok())
        .filter(|v| v.get("trace_id").and_then(|t| t.as_str()) == Some(trace_id))
        .collect()
}

/// The trace id of the most recent stage event in `walk_metrics.jsonl` (the walk that is running now, or ran last). Streams the file and keeps
/// the last row that carries a trace id; `None` when there is no such row. Read-only.
pub fn latest_trace_id() -> Option<String> {
    let f = std::fs::File::open(data_dir().join("walk_metrics.jsonl")).ok()?;
    let mut last: Option<String> = None;
    for line in std::io::BufReader::new(f).lines().map_while(Result::ok) {
        if let Some(t) = serde_json::from_str::<Value>(&line).ok().and_then(|v| v.get("trace_id").and_then(|t| t.as_str()).map(|s| s.to_string())) {
            last = Some(t);
        }
    }
    last
}

/// `GET /callgraph/live` for one trace: executed calls (shape rows) and stage events, oldest first.
pub fn live_for_trace(trace_id: &str) -> Value {
    let dir = data_dir();
    let mut calls = rows_for_trace(&dir.join("capture/call_spans.jsonl"), trace_id);
    calls.sort_by(|a, b| a["ts"].as_str().unwrap_or("").cmp(b["ts"].as_str().unwrap_or("")));
    let mut stages = rows_for_trace(&dir.join("walk_metrics.jsonl"), trace_id);
    stages.sort_by_key(|r| r["ts_ms"].as_u64().unwrap_or(0));
    // executed call sites: label -> {runs, failed, latency_ms of the last run}; rows with no call_site (entry-gate / routing verdict rows)
    // are reported as `unlabelled` so nothing is dropped
    let mut by_site = serde_json::Map::new();
    let mut unlabelled = 0u64;
    for c in &calls {
        match c["call_site"].as_str() {
            Some(site) => {
                let e = by_site.entry(site.to_string()).or_insert_with(|| json!({ "runs": 0, "failed": 0, "last_latency_ms": null }));
                let runs = e["runs"].as_u64().unwrap_or(0) + 1;
                let failed = e["failed"].as_u64().unwrap_or(0) + if c["success"].as_bool() == Some(false) { 1 } else { 0 };
                *e = json!({ "runs": runs, "failed": failed, "last_latency_ms": c["latency_ms"] });
            }
            None => unlabelled += 1,
        }
    }
    json!({
        "success": true,
        "trace_id": trace_id,
        "calls": calls,
        "stages": stages,
        "by_call_site": by_site,
        "unlabelled_calls": unlabelled,
        "note": "a call row is written when the call finishes; a call still in flight appears in the /ws pipeline_progress frames, not here",
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_for_trace_filters_by_exact_trace_id_and_streams_every_row() {
        let dir = std::env::temp_dir().join(format!("oz-cg-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let p = dir.join("spans.jsonl");
        std::fs::write(
            &p,
            concat!(
                "{\"trace_id\":\"t1\",\"call_site\":\"a\",\"success\":true,\"ts\":\"1\"}\n",
                "{\"trace_id\":\"t10\",\"call_site\":\"b\",\"success\":true,\"ts\":\"2\"}\n",
                "not json t1\n",
                "{\"trace_id\":\"t1\",\"call_site\":\"c\",\"success\":false,\"ts\":\"3\"}\n",
            ),
        )
        .unwrap();
        let rows = rows_for_trace(&p, "t1");
        assert_eq!(rows.len(), 2, "t10 shares the substring but is a different trace; the garbage line is skipped");
        assert_eq!(rows[1]["call_site"], "c");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn graph_body_carries_the_graph_and_the_generator_provenance() {
        let asset = json!({ "generator": "g", "inputs_sha256": "h", "notes": ["n"], "graphs": [] });
        let graph = json!({ "key": "walk", "title": "T", "nodes": [{"id": "a"}], "edges": [] });
        let body = graph_body(&asset, &graph);
        assert_eq!(body["kind"], "system_call_graph");
        assert_eq!(body["key"], "walk");
        assert_eq!(body["nodes"].as_array().unwrap().len(), 1);
        assert_eq!(body["inputs_sha256"], "h");
    }

    #[test]
    fn hash_is_stable_and_changes_with_content() {
        assert_eq!(hash_hex("x"), hash_hex("x"));
        assert_ne!(hash_hex("x"), hash_hex("y"));
    }

    #[test]
    fn container_points_at_its_body_and_is_global() {
        let c = build_container("walk", "Walk", "call_graphs/walk.json", 7);
        assert_eq!(c.global_state.parent_id, 0);
        assert_eq!(c.local_state.storage.object_store_path.as_deref(), Some("call_graphs/walk.json"));
        assert_eq!(c.local_state.metadata.materialized_path.as_deref(), Some("/CallGraphs/walk"));
    }
}
